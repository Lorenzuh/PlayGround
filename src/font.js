export const GLYPH_W = 5;
export const GLYPH_H = 7;
export const LETTER_SPACING = 1;

export function textWidth(str, scale = 1, spacing = LETTER_SPACING) {
  const s = String(str).toUpperCase();
  if (!s.length) return 0;
  return s.length * (GLYPH_W + spacing) * scale - spacing * scale;
}

/**
 * Draw pixel text with optional shadow/outline.
 * opts: { color, align:'left'|'center'|'right', scale, shadow, shadowColor,
 *         outline, outlineColor, spacing, alpha }
 */
export function drawText(ctx, str, x, y, opts = {}) {
  const {
    color = '#f7e6bd',
    align = 'left',
    scale = 1,
    shadow = 0,
    shadowColor = 'rgba(20,8,14,0.75)',
    outline = 0,
    outlineColor = '#1a1016',
    spacing = LETTER_SPACING,
    alpha = 1,
    baseline = 'top',
  } = opts;

  const s = String(str).toUpperCase();
  const w = textWidth(s, scale, spacing);
  let px = Math.round(x);
  if (align === 'center') px = Math.round(x - w / 2);
  else if (align === 'right') px = Math.round(x - w);
  let py = Math.round(y);
  if (baseline === 'middle') py = Math.round(y - (GLYPH_H * scale) / 2);
  else if (baseline === 'bottom') py = Math.round(y - GLYPH_H * scale);

  ctx.save();
  ctx.globalAlpha = alpha;
  ctx.fillStyle = color;

  const paint = (ox, oy, col) => {
    ctx.fillStyle = col;
    let cx = px + ox;
    for (const ch of s) {
      const glyph = G[ch] || G['?'];
      for (let gy = 0; gy < GLYPH_H; gy++) {
        const row = glyph[gy];
        for (let gx = 0; gx < GLYPH_W; gx++) {
          if (row[gx] === '1') ctx.fillRect(cx + gx * scale, py + oy + gy * scale, scale, scale);
        }
      }
      cx += (GLYPH_W + spacing) * scale;
    }
  };

  if (outline > 0) {
    for (let dx = -outline; dx <= outline; dx++) {
      for (let dy = -outline; dy <= outline; dy++) {
        if (dx === 0 && dy === 0) continue;
        paint(dx * scale, dy * scale, outlineColor);
      }
    }
  }
  if (shadow > 0) paint(shadow * scale, shadow * scale, shadowColor);
  paint(0, 0, color);
  ctx.restore();
  return w;
}

/** Word-wrapped centered text. Returns total height. */
export function drawWrapped(ctx, str, x, y, maxWidth, opts = {}) {
  const words = String(str).toUpperCase().split(' ');
  const scale = opts.scale || 1;
  const lineH = (GLYPH_H + (opts.lineGap ?? 3)) * scale;
  const lines = [];
  let line = '';
  for (const word of words) {
    const test = line ? line + ' ' + word : word;
    if (textWidth(test, scale) > maxWidth && line) {
      lines.push(line);
      line = word;
    } else line = test;
  }
  if (line) lines.push(line);
  lines.forEach((l, i) => drawText(ctx, l, x, y + i * lineH, opts));
  return lines.length * lineH;
}
